"""09 -- Build Word (.docx) and PDF versions of the paper from paper.md.

Pipeline: paper.md -> (figure sizing + YAML metadata) -> pandoc -> .docx
          .docx -> LibreOffice headless -> .pdf

Figure widths are set so that each image keeps its aspect ratio and fits the
printable width of both A4 and US Letter with 1-inch margins (6.2 in).

Requires pandoc and LibreOffice on PATH.
"""
import os
import re
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
BUILD = os.path.join(ROOT, "build")
DIST = os.path.join(ROOT, "dist")
MAX_WIDTH_IN = 6.2
NOMINAL_DPI = 160

TITLE = ("Somatic CAG-repeat expansion as a druggable rate process in "
         "Huntington's disease")
SUBTITLE = ("A multiscale in silico model linking MutSβ biochemistry, "
            "striatal neuron loss, and the delivery gap for MSH3-lowering "
            "oligonucleotides")


# Prose-only substitutions. Applied outside fenced code blocks and inline code
# spans, so file names such as 07_sensitivity.py are never touched.
#   - the arrow glyph has no coverage in LibreOffice's default PDF font and
#     renders as a stray dash, so it is spelled out
#   - underscores are turned into real subscripts
SUBS = [
    ("→", " to "),
    ("m^k", "*m*^k^"), ("2^k", "2^k^"), ("L_C", "L~C~"),
    ("K_D,b", "K~D,b~"), ("K_D", "K~D~"), ("K_r", "K~r~"),
    ("k_nca", "k~nca~"), ("L_pen", "L~pen~"), ("L_commit", "L~commit~"),
    ("L_sw", "L~sw~"), ("w_sw", "w~sw~"), ("f_lost", "f~lost~"),
    ("f_v", "f~v~"), ("L_death", "L~death~"), ("h_max", "h~max~"),
]


def apply_substitutions(text):
    """Apply SUBS to prose only, leaving fenced blocks and `code` spans alone."""
    out = []
    for i, chunk in enumerate(re.split(r"(```.*?```)", text, flags=re.S)):
        if i % 2:                      # fenced code block
            out.append(chunk)
            continue
        parts = []
        for j, piece in enumerate(re.split(r"(`[^`\n]*`)", chunk)):
            if j % 2:                  # inline code span
                parts.append(piece)
                continue
            for old, new in SUBS:
                piece = piece.replace(old, new)
            parts.append(piece)
        out.append("".join(parts))
    return "".join(out)


def png_size(path):
    with open(path, "rb") as f:
        head = f.read(33)
    return struct.unpack(">II", head[16:24])


def main():
    os.makedirs(BUILD, exist_ok=True)
    os.makedirs(DIST, exist_ok=True)

    with open(os.path.join(ROOT, "paper.md"), encoding="utf-8") as f:
        text = f.read()

    # Drop the hand-written title block; it becomes pandoc metadata instead.
    marker = "\n## Abstract"
    idx = text.index(marker)
    body = text[idx:]

    # Size every figure: keep aspect ratio, cap at the printable width.
    def size_image(m):
        alt, rel = m.group(1), m.group(2)
        w_px, _ = png_size(os.path.join(ROOT, rel))
        width = min(MAX_WIDTH_IN, w_px / NOMINAL_DPI)
        # empty alt text: the paper supplies its own caption paragraph under
        # each image, so pandoc must not add a second, auto-numbered one
        del alt
        return f"![]({rel}){{width={width:.2f}in}}"

    body, n = re.subn(r"!\[([^\]]*)\]\(([^)]+\.png)\)", size_image, body)
    print(f"sized {n} figures")
    body = apply_substitutions(body)
    # drop the markdown section rules; headings already separate the sections
    body = re.sub(r"^---$\n", "", body, flags=re.M)

    front = (
        "---\n"
        f'title: "{TITLE}"\n'
        f'subtitle: "{SUBTITLE}"\n'
        'author: "Shubho"\n'
        'date: "10 October 2026"\n'
        "lang: en-GB\n"
        "---\n\n"
        "*Computational research project. No wet-lab work: all results were "
        "generated by simulation and by analysis of published summary "
        "statistics.*\n"
    )

    md_path = os.path.join(BUILD, "paper_build.md")
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(front + body)

    docx_path = os.path.join(DIST, "Huntington_somatic_expansion_model.docx")
    cmd = ["pandoc", md_path, "-o", docx_path,
           "--from", "markdown+pipe_tables+subscript+superscript",
           "--resource-path", ROOT,
           "--metadata", "reference-section-title=References"]
    print("running:", " ".join(cmd))
    subprocess.run(cmd, check=True, cwd=ROOT)
    print("wrote", docx_path, os.path.getsize(docx_path), "bytes")

    cmd = ["soffice", "--headless", "--norestore", "--convert-to", "pdf",
           "--outdir", DIST, docx_path]
    print("running:", " ".join(cmd))
    subprocess.run(cmd, check=True, cwd=BUILD,
                   env={**os.environ, "HOME": BUILD})
    pdf_path = docx_path[:-5] + ".pdf"
    if not os.path.exists(pdf_path):
        sys.exit("PDF conversion produced no file")
    print("wrote", pdf_path, os.path.getsize(pdf_path), "bytes")


if __name__ == "__main__":
    main()
